print("Hello")

# Subscripting
print("Hello"[0])  # "H" - indexing starts at 0
print("Hello"[-1])  # "o" - negative indexing

print("123" + "345")  # "123345" - concatenation - "" means it's still a string
print(123 + 345)  # 468 - addition - no "" means it's an integer

print(123_456_789)  # 123456789 - underscores can be used for readability in numbers

# Floats
print(3.14159)  # 3.14159 - a float is a number with a decimal point

# Boolean - only 2 values
print(True)
print(False)

# Checking Data types
print(type(123))
print(type("Hello"))
print(type(23.4566))
print(type(True))
